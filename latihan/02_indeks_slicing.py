# Latihan 2: Indeks dan Slicing

nilai = [75, 80, 65, 90, 88]

# Mengakses elemen berdasarkan indeks
print("Nilai pertama:", nilai[0])
print("Nilai ketiga:", nilai[2])
print("Nilai terakhir:", nilai[-1])

# Mengambil sebagian elemen menggunakan slicing
print("Tiga nilai pertama:", nilai[:3])
print("Nilai indeks 1 sampai 3:", nilai[1:4])