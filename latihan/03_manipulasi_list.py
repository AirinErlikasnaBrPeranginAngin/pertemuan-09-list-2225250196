# Latihan 3: Manipulasi List

nilai = [75, 80, 65, 90, 88]

# Menambahkan nilai baru
nilai.append(95)
print("Setelah menambahkan nilai:", nilai)

# Mengubah nilai pada indeks tertentu
nilai[1] = 85
print("Setelah mengubah nilai:", nilai)

# Menghapus nilai berdasarkan isi
nilai.remove(65)
print("Setelah menghapus nilai 65:", nilai)

# Mengurutkan nilai dari kecil ke besar
nilai.sort()
print("Setelah diurutkan:", nilai)